# Builds a standalone harness from src/wheel.cpp by EXTRACTING the real blocks.
# Nothing here is retyped: if a block cannot be found the generator fails loudly
# rather than silently testing a stale copy of the code.
#
#   cd /tmp && python3 <repo>/tools/wheel-dog-harness.py
#   g++ -std=c++11 -O1 -o h h.cpp
#   ./h 1     # which strokes of the turn fire, across DOG and across CRANK
#   ./h 2     # the ripple profile: shape, depth, and the seam
import re, sys, os
SRC = open(os.path.join(os.path.dirname(os.path.abspath(__file__)),
                        '..', 'src', 'wheel.cpp')).read()
OUT = os.getcwd()

def grab(pat, label, flags=re.S):
    m = re.search(pat, SRC, flags)
    if not m: sys.exit("EXTRACT FAILED: " + label)
    return m.group(0)

def between(start, end, label):
    a = SRC.find(start)
    if a < 0: sys.exit("EXTRACT FAILED (start): " + label)
    b = SRC.find(end, a)
    if b < 0: sys.exit("EXTRACT FAILED (end): " + label)
    return SRC[a:b + len(end)]

seam   = grab(r'static const float WH_SEAM = [0-9.]+f;', 'WH_SEAM')
justtab= grab(r'static const float WH_JUST\[12\] = \{.*?\};', 'WH_JUST')
justfn = grab(r'static inline float wheelJustify\(float semis\) \{.*?\n\}', 'wheelJustify()')
maxc   = grab(r'static const int WH_MAXCOUPS = \d+;[^\n]*', 'WH_MAXCOUPS')
gcdfn  = grab(r'static inline int wheelGcd\(int a, int b\) \{[^\n]*\}', 'wheelGcd()')
accent = grab(r'static inline float wheelAccent\(int k, int n\) \{.*?\n\}', 'wheelAccent()')
# The two places the ripple reaches the sound, lifted as expressions so mode 3
# measures what the engine actually applies rather than a description of it.
press  = grab(r'struct WheelPress \{.*?\n\};', 'WheelPress')
ampF   = grab(r'clamp\(1\.f \+ depth \* r \* [0-9.]+f, [0-9.]+f, [0-9.]+f\)', 'ripple->amp')
brightF= grab(r'clamp\(1\.f \+ [0-9.]+f \* depth \* r, [0-9.]+f, [0-9.]+f\)', 'ripple->bright')
ripple = grab(r'\tfloat rippleAt\(double ph\) const \{.*?\n\t\}', 'rippleAt()')

# The crank/coup/dog block, exactly as process() runs it. Cut at the boundaries
# of the two sections so the harness cannot drift from the engine.
crank = between('\t\tdouble prevPhase = wheelPhase;',
                '\t\tfloat rattleGate = (rattle < 0.42) ? 1.f : 0.f;', 'crank+coup+dog')
# strip the two lines that need Rack inputs; the harness drives them directly
crank = crank.replace(
    '\t\tif (coupTrig.process(inputs[COUP_INPUT].getVoltage(), 0.1f, 1.f)) stroke = 1.2f;',
    '\t\tif (coupIn) stroke = 1.2f;')
crank = re.sub(r'\t\tfloat dogK = params\[DOG_PARAM\]\.getValue\(\);\n'
               r'\t\tif \(inputs\[DOG_INPUT\]\.isConnected\(\)\).*?\n'
               r'\t\tdogK = clamp\(dogK, 0\.f, 1\.f\);\n', '', crank)
crank = re.sub(r'\t\tfloat decayS = 0\.04f \+ 0\.11f \* params\[DECAY_PARAM\]\.getValue\(\);',
               '\t\tfloat decayS = 0.04f + 0.11f * 0.4f;', crank)
# COUPS is read above the extracted range, so the harness sets `coups` itself.
# `random` is a function in macOS's <stdlib.h>, so the namespace is renamed
# rather than shadowed. A pure rename: no behaviour rides on it.
crank = crank.replace('random::', 'rnd::')
if 'dogK' not in crank:            sys.exit("EXTRACT FAILED: dogK vanished with the strip")
if 'params[DOG_PARAM]' in crank:   sys.exit("EXTRACT FAILED: dogK read not stripped")
if 'inputs[' in crank:             sys.exit("EXTRACT FAILED: an unsubstituted Rack input remains")
if 'params[' in crank:             sys.exit("EXTRACT FAILED: an unsubstituted Rack param remains")

